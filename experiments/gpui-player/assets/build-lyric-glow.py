"""Generate cached glyph-outline shadows, matching CSS text-shadow 0 0 14px amber."""
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
root=Path(__file__).resolve().parent
font=TTFont(root/'Bricolage650.ttf');glyphs=font.getGlyphSet();cmap=font.getBestCmap()
scale=18.025/font['head'].unitsPerEm
lh=25.375*1.03;pad=21
asc=font['hhea'].ascent*scale;desc=-font['hhea'].descent*scale
baseline=(lh-asc-desc)/2+asc
words='Let the city fade away Find a little room to breathe Every note will light way Sing song you carry underneath moment find its place And begin again with me'.split()
out=root/'glow';out.mkdir(exist_ok=True)
rust=['// Generated by assets/build-lyric-glow.py. Cached outline masks, not UI text.','pub fn mask(word: &str) -> Option<&\'static [u8]> { Some(match word {']
for index,word in enumerate(dict.fromkeys(words)):
 x=0;paths=[]
 for ch in word:
  name=cmap[ord(ch)];pen=SVGPathPen(glyphs);glyphs[name].draw(pen)
  paths.append(f'<path transform="translate({pad+x} {pad+baseline}) scale({scale} {-scale})" d="{pen.getCommands()}"/>')
  x+=font['hmtx'][name][0]*scale
 svg=f'<svg xmlns="http://www.w3.org/2000/svg" width="{x+2*pad}" height="{lh+2*pad}" viewBox="0 0 {x+2*pad} {lh+2*pad}"><defs><filter id="glow" x="-100%" y="-200%" width="300%" height="500%" color-interpolation-filters="sRGB"><feGaussianBlur stdDeviation="7"/></filter></defs><g filter="url(#glow)" fill="white">'+''.join(paths)+'</g></svg>'
 (out/f'{index}.svg').write_text(svg)
 rust.append(f'    "{word}" => include_bytes!("../assets/glow/{index}.svg"),')
rust+=['    _ => return None,','}) }']
(root.parent/'src/lyric_glow.rs').write_text('\n'.join(rust)+'\n')
