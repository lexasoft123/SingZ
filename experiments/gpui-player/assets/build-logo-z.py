#!/usr/bin/env python3
"""Outline the exact bundled Z and apply Chromium's CSS synthetic italic skew.

Chromium's mac FontPlatformData::CreateSkFont uses
    skfont.setSkewX(synthetic_italic_ ? -SK_Scalar1 / 4 : 0)
https://raw.githubusercontent.com/chromium/chromium/main/third_party/blink/renderer/platform/fonts/mac/font_platform_data_mac.mm

Screen y points down; font outline y points up, hence x' = x + .25*y.
The advance is unchanged, exactly as synthetic italic in Chromium. Transparent
overscan retains the glyph's right overhang instead of changing its advance.
Requires the same fontTools environment used by instance-fonts.py.
"""
from hashlib import sha256
from math import ceil, floor
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

ROOT = Path(__file__).resolve().parent
FONT = ROOT / "Bricolage800.ttf"
font = TTFont(FONT)
glyphs = font.getGlyphSet()
glyph = glyphs[font.getBestCmap()[ord("Z")]]
units = font["head"].unitsPerEm
font_size = 17.
compiled_dpr = 2.
# Same normal-line metrics as Blink: round in device-scaled units first.
ascent = floor(font["hhea"].ascent / units * font_size * compiled_dpr + .5) / compiled_dpr
descent = floor(-font["hhea"].descent / units * font_size * compiled_dpr + .5) / compiled_dpr
line_height = ascent + descent
line_units = line_height / font_size * units
baseline = ascent / font_size * units
transform = (1, 0, .25, -1, 0, baseline)
bounds = BoundsPen(glyphs)
glyph.draw(TransformPen(bounds, transform))
width = ceil(bounds.bounds[2] * font_size / units + 1)
svg_width = width / font_size * units
pen = SVGPathPen(glyphs)
glyph.draw(TransformPen(pen, transform))
path = ROOT / "icons/header-logo-z.svg"
path.write_text(
    f'<!-- Generated by build-logo-z.py; font SHA256 {sha256(FONT.read_bytes()).hexdigest()}; '
    f'Blink CSS normal metrics DPR{compiled_dpr:g}: ascent/baseline {ascent:g}px, descent {descent:g}px. -->\n'
    f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {svg_width:.12f} {line_units:.12f}" fill="currentColor">'
    f'<path d="{pen.getCommands()}"/></svg>\n'
)
print(f"advance including .02em tracking: {glyph.width * font_size / units + font_size * .02:.12f}px")
print(f"SVG paint box: {width} × {line_height}px; baseline {baseline * font_size / units:.12f}px")
print(path)
