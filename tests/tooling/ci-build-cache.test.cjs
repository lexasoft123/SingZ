const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const os = require('node:os')
const crypto = require('node:crypto')
const { createState, readState, parseStats, deltaStats, nativeEvidence, validArchiveStore, main } = require('../../scripts/ci-build-cache.cjs')

const env = { CACHE_PLATFORM: 'ios', CACHE_ARCHIVES: 'true', RUNNER_OS: 'macOS', RUNNER_ARCH: 'ARM64', CACHE_TOOLCHAIN: 'xcode-26',
  CACHE_DEPS: 'deps', CACHE_SOURCES: 'native', CACHE_METRO_SOURCES: 'javascript', GITHUB_JOB: 'publish', GITHUB_RUN_ID: '101', GITHUB_RUN_ATTEMPT: '1' }
function scratch(t) {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'singz-ci-cache-'))
  t.after(() => fs.rmSync(directory, { recursive: true, force: true }))
  return directory
}
test('CI counters accept distro ccache TSV without requiring newer JSON options', () => {
  const before = parseStats('cache_miss\t12\ndirect_cache_hit\t3\npreprocessed_cache_hit\t1\ncalled_for_link\t7\n')
  const after = parseStats('cache_miss\t13\ndirect_cache_hit\t5\npreprocessed_cache_hit\t1\ncalled_for_link\t7\n')
  assert.deepEqual(deltaStats(before, after), { cache_miss: 1, direct_cache_hit: 2, preprocessed_cache_hit: 0, called_for_link: 0 })
  assert.throws(() => parseStats('cache_miss\t12\n'), /Missing/)
  assert.throws(() => parseStats('cache_miss\tnot-a-number\n'), /Malformed/)
})
test('mutable CI stores keep new generations while compatible restore prefixes remain reusable', () => {
  const first = createState(env, '/home/runner'), next = createState({ ...env, GITHUB_RUN_ID: '102' }, '/home/runner')
  for (const kind of ['compiler', 'gradle', 'metro', 'archives']) {
    assert.notEqual(first.caches[kind].key, next.caches[kind].key)
    assert.ok(first.caches[kind].key.startsWith(next.caches[kind].restore[0]))
  }
  for (const kind of ['audio', 'pods']) assert.equal(first.caches[kind].key, next.caches[kind].key, 'pinned downloads do not multiply on every run')
  assert.notEqual(first.caches.compiler.key, createState({ ...env, CACHE_TOOLCHAIN: 'xcode-27' }).caches.compiler.key)
  assert.notEqual(first.caches.metro.key, createState({ ...env, CACHE_METRO_SOURCES: 'changed-js' }).caches.metro.key)
  assert.equal(first.caches.compiler.key, createState({ ...env, CACHE_METRO_SOURCES: 'changed-js' }, '/home/runner').caches.compiler.key)
})
test('CI persists React Native tarballs and stable Metro storage, but not mutable native build state', () => {
  const state = createState(env, '/home/runner')
  assert.match(state.caches.pods.path, /Caches[/\\]ReactNative/)
  assert.match(state.caches.metro.path, /Caches[/\\]SingZ[/\\]metro$/)
  assert.match(state.caches.archives.path, /\*\/SingZ\.xcarchive$/)
  assert.doesNotMatch(JSON.stringify(state.caches), /DerivedData|node_modules|\.cxx|\.xcresult/)
  assert.equal(createState({ ...env, CACHE_PLATFORM: 'android' }).caches.pods.enabled, false)
  assert.equal(createState({ ...env, CACHE_ARCHIVES: 'false' }).caches.archives.enabled, false)
  assert.throws(() => createState({ ...env, CACHE_SOURCES: 'bad\nkey' }), /identity/)
  assert.throws(() => readState('{"version":99}'), /state/)
})
test('cache use accepts cold compiler misses and valid whole-output reuse but rejects bypasses', () => {
  assert.equal(nativeEvidence({ cache_miss: 5 }, ''), 'compiler cache invoked')
  assert.equal(nativeEvidence({ direct_cache_hit: 5 }, ''), 'compiler cache invoked')
  const cached = 'Native inputs unchanged: rebundling JavaScript and exporting cached archive\nSuccessfully exported and signed the ipa file:'
  assert.equal(nativeEvidence({}, cached), 'validated native archive reused')
  assert.equal(nativeEvidence({}, cached + '\nCached export failed; rebuilding'), null)
  assert.equal(nativeEvidence({}, 'Native inputs unchanged: rebundling JavaScript and exporting cached archive'), null)
  assert.equal(nativeEvidence({}, '> Task :app:buildCMakeRelease[arm64-v8a] FROM-CACHE\n> Task :library:buildCMakeRelease[arm64-v8a] UP-TO-DATE'), 'native Gradle outputs reused')
  assert.equal(nativeEvidence({}, '> Task :app:buildCMakeRelease[arm64-v8a]\n> Task :lib:buildCMakeRelease[x86_64] FROM-CACHE'), null)
  assert.equal(nativeEvidence({ called_for_link: 1 }, '> Task :app:compileDebugKotlin FROM-CACHE'), null)
  assert.deepEqual(deltaStats({ cache_miss: 10 }, { cache_miss: 12, direct_cache_hit: 1 }), { cache_miss: 2, direct_cache_hit: 1 })
  assert.throws(() => deltaStats({ cache_miss: 10 }, { cache_miss: 0 }), /reset/)
})
test('archive saves accept only receipt- and signature-verified atomic archives', t => {
  const directory = scratch(t), key = 'a'.repeat(64), archive = path.join(directory, key, 'SingZ.xcarchive')
  const app = path.join(archive, 'Products/Applications/SingZPlayer.app')
  fs.mkdirSync(app, { recursive: true })
  fs.writeFileSync(path.join(app, 'SingZPlayer'), 'signed binary')
  fs.writeFileSync(path.join(app, 'Info.plist'), 'metadata'); fs.writeFileSync(path.join(archive, 'Info.plist'), 'metadata')
  fs.writeFileSync(path.join(archive, '.singz-native-inputs.json'), JSON.stringify({ format: 1, inputs: key, binary: crypto.createHash('sha256').update('signed binary').digest('hex') }))
  fs.mkdirSync(path.join(directory, 'b'.repeat(64), 'SingZ.xcarchive.partial'), { recursive: true })
  assert.deepEqual(validArchiveStore(directory, () => true), { valid: 1, invalid: 0 })
  assert.deepEqual(validArchiveStore(directory, () => false), { valid: 0, invalid: 1 })
  fs.writeFileSync(path.join(app, 'SingZPlayer'), 'tampered')
  assert.deepEqual(validArchiveStore(directory, () => true), { valid: 0, invalid: 1 })
  fs.mkdirSync(path.join(directory, 'unrecognized', 'SingZ.xcarchive'), { recursive: true })
  assert.deepEqual(validArchiveStore(directory, () => true), { valid: 0, invalid: 2 })
})
test('finalization preserves completed work after failure but never freezes partial pinned downloads', t => {
  const home = scratch(t), state = createState({ ...env, RUNNER_TEMP: home }, home)
  const output = path.join(home, 'outputs')
  for (const kind of ['compiler', 'audio', 'pods', 'metro']) for (const directory of state.caches[kind].path.split('\n')) fs.mkdirSync(directory, { recursive: true })
  main(['finalize'], { SINGZ_CI_CACHE_STATE: JSON.stringify(state), GITHUB_OUTPUT: output })
  let values = fs.readFileSync(output, 'utf8')
  assert.match(values, /compiler-save<<[^\n]+\ntrue\n/)
  assert.match(values, /audio-save<<[^\n]+\nfalse\n/)
  fs.mkdirSync(state.reportDir, { recursive: true }); fs.writeFileSync(path.join(state.reportDir, 'ios-baseline.json'), '{}')
  fs.writeFileSync(output, '')
  main(['finalize'], { SINGZ_CI_CACHE_STATE: JSON.stringify(state), GITHUB_OUTPUT: output })
  assert.match(fs.readFileSync(output, 'utf8'), /audio-save<<[^\n]+\ntrue\n/)
  state.caches.audio.matched = state.caches.audio.key; fs.writeFileSync(output, '')
  main(['finalize'], { SINGZ_CI_CACHE_STATE: JSON.stringify(state), GITHUB_OUTPUT: output })
  assert.match(fs.readFileSync(output, 'utf8'), /audio-save<<[^\n]+\nfalse\n/)
})
