#!/usr/bin/env node
/**
 * Bundle SingZ's platform-neutral vocal-training core for Metro.
 *
 * Metro intentionally stays rooted in mobile/ (widening it pulls a second
 * React installation into resolution). This generated ESM file is therefore
 * the phone's runtime view of the exact desktop/shared implementation. Types
 * re-export the source declarations so they cannot drift independently.
 */
import { createRequire } from 'node:module'
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const mobileRoot = resolve(here, '..')
const repoRoot = resolve(mobileRoot, '..')
const outDir = join(mobileRoot, 'src', 'gen')

let esbuild
try {
  esbuild = createRequire(join(mobileRoot, 'package.json'))('esbuild')
} catch {
  esbuild = createRequire(join(repoRoot, 'package.json'))('esbuild')
}

const banner = `// GENERATED by mobile/scripts/build-training.mjs — do not edit.
// One runtime source for desktop and mobile vocal training.
// Regenerate: node mobile/scripts/build-training.mjs`

mkdirSync(outDir, { recursive: true })
await esbuild.build({
  stdin: {
    contents: `
export * from './shared/music-theory'
export * from './shared/training-types'
export * from './shared/training-session'
export * from './shared/training-scoring'
export * from './shared/training-progress'
export * from './shared/training-preparation'
export { yinPitchInfo } from './renderer/src/audio/pitch'
`,
    resolveDir: join(repoRoot, 'src'),
    loader: 'ts'
  },
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2020',
  outfile: join(outDir, 'training-lib.js'),
  banner: { js: banner },
  logLevel: 'warning'
})

writeFileSync(
  join(outDir, 'training-lib.d.ts'),
  `${banner}
export * from '../../../src/shared/music-theory'
export * from '../../../src/shared/training-types'
export * from '../../../src/shared/training-session'
export * from '../../../src/shared/training-scoring'
export * from '../../../src/shared/training-progress'
export * from '../../../src/shared/training-preparation'
export { yinPitchInfo, type PitchFrame } from '../../../src/renderer/src/audio/pitch'
`
)

console.log('build-training: wrote mobile/src/gen/training-lib.{js,d.ts}')
