#!/usr/bin/env node
/**
 * Bundle the DESKTOP analysis sources for the phone — verbatim, not ported.
 *
 * detectBeats/courts, the melody codec and the pYIN tracker core are
 * dependency-free TypeScript (the beat eval harness already runs them under
 * plain node), so the phone gets the exact same code — and, critically, the
 * exact same BEAT_DETECT_VERSION / PITCH_DETECT_VERSION constants: a phone
 * can never stamp a stale version, because the stamp rides in this bundle.
 *
 * Output (mobile/src/gen/, gitignored — same policy as gdrive-config.ts):
 *   analysis-lib.js    ESM bundle Metro/jest consume
 *   analysis-lib.d.ts  hand-maintained surface below, emitted alongside
 *
 * Runs from mobile's postinstall. esbuild is a mobile devDependency (CI
 * installs mobile/ alone — the android.yml canary), with the desktop root's
 * copy as a dev-machine fallback while node_modules is mid-install.
 */
import { createRequire } from 'node:module'
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const mobileRoot = resolve(here, '..')
const repoRoot = resolve(mobileRoot, '..')
const audioDir = join(repoRoot, 'src', 'renderer', 'src', 'audio')
const outDir = join(mobileRoot, 'src', 'gen')

let esbuild
try {
  esbuild = createRequire(join(mobileRoot, 'package.json'))('esbuild')
} catch {
  try {
    esbuild = createRequire(join(repoRoot, 'package.json'))('esbuild')
  } catch {
    console.error('build-analysis: esbuild not found — `npm ci` in mobile/ (or the repo root) first.')
    process.exit(1)
  }
}

const banner = `// GENERATED by mobile/scripts/build-analysis.mjs — do not edit.
// Bundles src/renderer/src/audio/{analysis,courts,melody,pitch-core,pyin,pitch}.ts
// verbatim so the phone runs the desktop's own detectors at the desktop's own
// version stamps. Regenerate: node mobile/scripts/build-analysis.mjs`

const entry = `
export { detectBeats, estimateKey, BEAT_DETECT_VERSION } from './analysis'
export { encodeMelody, decodeMelody, melodyFitsSong, PITCH_DETECT_VERSION } from './melody'
export { trackMelodyCore } from './pitch-core'
`

mkdirSync(outDir, { recursive: true })
await esbuild.build({
  stdin: { contents: entry, resolveDir: audioDir, loader: 'ts' },
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2020',
  outfile: join(outDir, 'analysis-lib.js'),
  banner: { js: banner },
  logLevel: 'warning'
})

// The type surface, by hand: the sources type against the DOM AudioBuffer,
// which mobile's tsconfig has no lib for — the structural stand-in below is
// what the code actually touches (the eval harness feeds a 6-line duck).
writeFileSync(
  join(outDir, 'analysis-lib.d.ts'),
  `${banner}

/** Structural AudioBuffer — react-native-audio-api's satisfies it. */
export interface AudioBufferLike {
  sampleRate: number
  length: number
  duration: number
  numberOfChannels: number
  getChannelData(channel: number): Float32Array
}

export interface KeyGuess {
  pc: number
  minor: boolean
}

export interface DetectedBeats {
  beats: number[]
  bpm: number
  beatsPerBar: number
  downbeat: number
  downbeats?: number[]
  suspectAt?: number[]
}

export interface MlGrid {
  beats: number[]
  downbeats: number[]
  beatProb?: number[]
  downbeatProb?: number[]
  fps?: number
}

export interface BeatAux {
  bass?: AudioBufferLike | null
  vocals?: AudioBufferLike | null
  lineStarts?: number[] | null
  words?: { s: number; e: number }[] | null
  inst?: AudioBufferLike[] | null
  ml?: MlGrid | null
}

export interface MelodyInfo {
  detVersion: number
  hopSec: number
  f0: string
}

export interface MelodyTrack {
  f0: Float32Array
  raw: Float32Array
  rms: Float32Array
  hopSec: number
}

export declare const BEAT_DETECT_VERSION: number
export declare const PITCH_DETECT_VERSION: number
export declare function detectBeats(
  buffer: AudioBufferLike,
  aux?: BeatAux,
  debug?: Record<string, unknown>
): DetectedBeats | null
export declare function estimateKey(f0: Float32Array): KeyGuess | null
export declare function encodeMelody(f0: Float32Array, hopSec: number): MelodyInfo
export declare function decodeMelody(
  raw: unknown
): { info: MelodyInfo; f0: Float32Array } | null
export declare function melodyFitsSong(
  f0: Float32Array,
  hopSec: number,
  durationSec: number
): boolean
export declare function trackMelodyCore(
  mono: Float32Array,
  sampleRate: number,
  onProgress?: (p: number) => void
): MelodyTrack
`
)

console.log('build-analysis: wrote mobile/src/gen/analysis-lib.{js,d.ts}')
