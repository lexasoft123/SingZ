#!/usr/bin/env node
/**
 * Bundle the DESKTOP analysis sources for the phone — verbatim, not ported.
 *
 * detectBeats/courts, the melody codec and the pYIN tracker core are
 * dependency-free TypeScript (the beat eval harness already runs them under
 * plain node), so the phone gets the exact same code — and, critically, the
 * exact same BEAT_DETECT_VERSION / PITCH_DETECT_VERSION constants: a phone
 * can never stamp a stale version, because the stamp rides in this bundle.
 *
 * Output (mobile/src/gen/, gitignored — same policy as gdrive-config.ts):
 *   analysis-lib.js        ESM bundle Metro/jest consume
 *   analysis-lib.d.ts      hand-maintained surface below, emitted alongside
 *   analysis-worklet.js    the detectors again, as ONE 'worklet' function
 *                          (see below) — for the background analysis runtime
 *   analysis-worklet.d.ts  its surface
 *
 * Runs from mobile's postinstall. esbuild is a mobile devDependency (CI
 * installs mobile/ alone — the android.yml canary), with the desktop root's
 * copy as a dev-machine fallback while node_modules is mid-install.
 */
import { createRequire } from 'node:module'
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const mobileRoot = resolve(here, '..')
const repoRoot = resolve(mobileRoot, '..')
const audioDir = join(repoRoot, 'src', 'renderer', 'src', 'audio')
const outDir = join(mobileRoot, 'src', 'gen')

let esbuild
try {
  esbuild = createRequire(join(mobileRoot, 'package.json'))('esbuild')
} catch {
  try {
    esbuild = createRequire(join(repoRoot, 'package.json'))('esbuild')
  } catch {
    console.error('build-analysis: esbuild not found — `npm ci` in mobile/ (or the repo root) first.')
    process.exit(1)
  }
}

const banner = `// GENERATED by mobile/scripts/build-analysis.mjs — do not edit.
// Bundles src/renderer/src/audio/{analysis,courts,melody,pitch-core,pyin,pitch}.ts
// verbatim so the phone runs the desktop's own detectors at the desktop's own
// version stamps. Regenerate: node mobile/scripts/build-analysis.mjs`

const entry = `
export { detectBeats, estimateKey, estimateKeyFromStems, BEAT_DETECT_VERSION, KEY_DETECT_VERSION } from './analysis'
export { encodeMelody, decodeMelody, melodyFitsSong, PITCH_DETECT_VERSION } from './melody'
export { trackMelodyCore } from './pitch-core'
export { applyUserBars } from './beat'
// Parity-only, and node-side ONLY (the worklet entry below does not take
// these): the courts' extractor layer, so eval/courts-parity.mjs can compare
// the C++ port against it directly. That layer leans on cos/sin/log2/log1p/
// hypot for its ANSWERS rather than for a window, and libm agreement with V8
// is an empirical property of the platform rather than anything the porting
// rules can enforce — so it is measured, not assumed.
export { to22k, fftComplex, chromaFrames, beatSyncChroma, rmsEnvelope, chordRuns, vocalEvidence, formSeams, buildCourtEvidence } from './courts'
// The DECIDING side, likewise parity-only: applyCourts is the entry point the
// app calls, so it is the one worth gating — the individual courts are
// internal to courts.ts and stay that way. changePoints and mlLevelStats come
// too because the C++ exposes them and a harness that could only see the
// composed answer would not say WHICH court moved.
export { applyCourts, changePoints, mlLevelStats } from './courts'
export {
  LRCLIB_API, LRCLIB_HEADERS, fixTagEncoding, realArtist, metaFromFilename,
  parseLrc, lookupLyrics, searchCandidates, lyricsById
} from '../../../shared/lrclib-core'
`

mkdirSync(outDir, { recursive: true })
await esbuild.build({
  stdin: { contents: entry, resolveDir: audioDir, loader: 'ts' },
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2020',
  outfile: join(outDir, 'analysis-lib.js'),
  banner: { js: banner },
  logLevel: 'warning'
})

// ---- the same detectors again, as ONE worklet ----
//
// Melody is ~65 s of straight-line arithmetic per song (the Phase-0 spike), so
// it runs on a worklet runtime and not on the thread drawing the app. Worklet
// runtimes are separate JS runtimes: they cannot see this app's modules and
// cannot share its memory, and Hermes has no eval to load code at runtime with.
// So the detectors travel as CODE — the whole bundle inlined in one function
// carrying the 'worklet' directive, which the worklets babel plugin serializes
// into the other runtime whole. That is a build-time answer to a runtime
// problem, and it costs no app-wide Bundle Mode switch.
//
// The lyrics half is deliberately absent: this bundle is arithmetic only, so it
// names no fetch, no AbortController and no timer that a worklet runtime would
// have to provide.
const workletEntry = `
export { detectBeats, estimateKey, estimateKeyFromStems, BEAT_DETECT_VERSION, KEY_DETECT_VERSION } from './analysis'
export { encodeMelody, melodyFitsSong, PITCH_DETECT_VERSION } from './melody'
export { trackMelodyCore } from './pitch-core'
export { applyUserBars } from './beat'
`

const iife = await esbuild.build({
  stdin: { contents: workletEntry, resolveDir: audioDir, loader: 'ts' },
  bundle: true,
  format: 'iife',
  globalName: 'lib',
  platform: 'neutral',
  target: 'es2020',
  write: false,
  logLevel: 'warning'
})
// esbuild emits `var lib = (() => { … })();` — a plain local declaration once
// it sits inside the function below, so the bundle never touches a global.
//
// Lowered with Babel's block-scoping transform FIRST, and this is not
// optional: the worklets plugin serializes a worklet's body as source and the
// worklet runtime evaluates that source raw, and Hermes gives every closure in
// a `for (let …)` loop the LAST iteration's binding — measured on the iOS
// simulator: `for (let k of ['a','b','c']) fns.push(() => k)` yields c,c,c.
// The app runtime never sees this because Metro's preset lowers block scoping
// before Hermes does; the worklet path bypasses the preset. Unlowered, the
// bundle's own module-export helper (a per-key getter closure in a for-of)
// resolved EVERY export to the last one, so `lib.detectBeats` was
// trackMelodyCore. The detectors themselves close over loop lets too, so the
// wrong answer would not always be as loud as that.
const babel = createRequire(join(mobileRoot, 'package.json'))('@babel/core')
const iifeSrc = babel
  .transformSync(iife.outputFiles[0].text, {
    babelrc: false,
    configFile: false,
    compact: false,
    plugins: [
      createRequire(join(mobileRoot, 'package.json')).resolve('@babel/plugin-transform-block-scoping')
    ]
  })
  .code.trimEnd()

// A .js with a .d.ts beside it, like analysis-lib: the body is transpiled
// output, which mobile's strict tsconfig would refuse as source (implicit
// anys throughout) — and the worklets babel plugin reads .js just the same.
const workletHead = `${banner}
//
// The worklet-runtime copy: \`loadAnalysisLib\` is one function with the whole
// bundle in its body and nothing in its closure, so it serializes into any
// worklet runtime as source. Compiling ~${Math.round(iifeSrc.length / 1024)} kB
// is not free, so the result is cached on that runtime's own global — the
// second song pays nothing.`

writeFileSync(
  join(outDir, 'analysis-worklet.js'),
  `${workletHead}

export function loadAnalysisLib() {
  'worklet'
  const g = globalThis
  if (g.__singzAnalysisLib) return g.__singzAnalysisLib
${iifeSrc
  .split('\n')
  .map((l) => (l ? `  ${l}` : l))
  .join('\n')}
  g.__singzAnalysisLib = lib
  return lib
}
`
)

writeFileSync(
  join(outDir, 'analysis-worklet.d.ts'),
  `${workletHead}

import type {
  AudioBufferLike,
  BeatAux,
  DetectedBeats,
  KeyGuess,
  MelodyInfo,
  MelodyTrack,
  StoredBeatInfo
} from './analysis-lib'

export interface AnalysisLib {
  BEAT_DETECT_VERSION: number
  PITCH_DETECT_VERSION: number
  KEY_DETECT_VERSION: number
  detectBeats(
    buffer: AudioBufferLike,
    aux?: BeatAux,
    debug?: Record<string, unknown>
  ): DetectedBeats | null
  /** Last resort only — the sung line is a poor witness to the key. */
  estimateKey(f0: Float32Array): KeyGuess | null
  estimateKeyFromStems(inst: AudioBufferLike[], bass: AudioBufferLike | null): KeyGuess | null
  encodeMelody(f0: Float32Array, hopSec: number): MelodyInfo
  melodyFitsSong(f0: Float32Array, hopSec: number, durationSec: number): boolean
  trackMelodyCore(
    mono: Float32Array,
    sampleRate: number,
    onProgress?: (p: number) => void
  ): MelodyTrack
  applyUserBars(info: StoredBeatInfo): StoredBeatInfo
}

/**
 * The detectors, on whichever runtime calls this. Marked 'worklet', so it can
 * be scheduled onto a worklet runtime as-is; on the app runtime it is an
 * ordinary function.
 */
export declare function loadAnalysisLib(): AnalysisLib
`
)

// The type surface, by hand: the sources type against the DOM AudioBuffer,
// which mobile's tsconfig has no lib for — the structural stand-in below is
// what the code actually touches (the eval harness feeds a 6-line duck).
writeFileSync(
  join(outDir, 'analysis-lib.d.ts'),
  `${banner}

/** Structural AudioBuffer — react-native-audio-api's satisfies it. */
export interface AudioBufferLike {
  sampleRate: number
  length: number
  duration: number
  numberOfChannels: number
  getChannelData(channel: number): Float32Array
}

export interface KeyGuess {
  pc: number
  minor: boolean
}

export interface DetectedBeats {
  beats: number[]
  bpm: number
  beatsPerBar: number
  downbeat: number
  downbeats?: number[]
  suspectAt?: number[]
}

export interface MlGrid {
  beats: number[]
  downbeats: number[]
  beatProb?: number[]
  downbeatProb?: number[]
  fps?: number
}

export interface BeatAux {
  bass?: AudioBufferLike | null
  vocals?: AudioBufferLike | null
  lineStarts?: number[] | null
  words?: { s: number; e: number }[] | null
  inst?: AudioBufferLike[] | null
  ml?: MlGrid | null
}

export interface MelodyInfo {
  detVersion: number
  hopSec: number
  f0: string
}

export interface MelodyTrack {
  f0: Float32Array
  raw: Float32Array
  rms: Float32Array
  hopSec: number
}

export declare const BEAT_DETECT_VERSION: number
export declare const PITCH_DETECT_VERSION: number
export declare const KEY_DETECT_VERSION: number
export declare function detectBeats(
  buffer: AudioBufferLike,
  aux?: BeatAux,
  debug?: Record<string, unknown>
): DetectedBeats | null
export declare function estimateKey(f0: Float32Array): KeyGuess | null
export declare function estimateKeyFromStems(
  inst: AudioBufferLike[],
  bass: AudioBufferLike | null
): KeyGuess | null
export declare function encodeMelody(f0: Float32Array, hopSec: number): MelodyInfo
export declare function decodeMelody(
  raw: unknown
): { info: MelodyInfo; f0: Float32Array } | null
export declare function melodyFitsSong(
  f0: Float32Array,
  hopSec: number,
  durationSec: number
): boolean
export declare function trackMelodyCore(
  mono: Float32Array,
  sampleRate: number,
  onProgress?: (p: number) => void
): MelodyTrack
/** Re-fold hand-placed bar lines (seconds) onto a freshly detected grid —
 *  the desktop's own rule, so a corrected song keeps receiving detector work. */
export declare function applyUserBars(info: StoredBeatInfo): StoredBeatInfo

/** The desktop's BeatInfo as project.json stores it (src/shared/types.ts). */
export interface StoredBeatInfo {
  beats: number[]
  bpm: number
  beatsPerBar: number
  downbeat: number
  downbeats?: number[]
  userBars?: number[]
  autoDownbeats?: number[]
  suspectAt?: number[]
  source: 'auto' | 'manual'
  detVersion?: number
}

// ---- LRCLIB core (src/shared/lrclib-core.ts) ----

export interface LyricWordLike {
  w: string
  s: number
  e: number
}

export interface LyricLineLike {
  start: number
  end: number
  text: string
  words: LyricWordLike[]
}

export interface TrackMeta {
  artist?: string
  title: string
  album?: string
  durationSec: number
  altTitle?: string
}

export type ApiAnswer = { json: unknown } | 'miss' | 'down'
export type ApiFetch = (path: string) => Promise<ApiAnswer>

export interface LyricsCandidate {
  id: number
  artist: string
  track: string
  album?: string
  duration: number
  synced: boolean
}

export type LookupOutcome =
  | { hit: { lines: LyricLineLike[]; credit: string } }
  | 'miss'
  | 'down'

export declare const LRCLIB_API: string
export declare const LRCLIB_HEADERS: Record<string, string>
export declare function fixTagEncoding(s: string | undefined): string | undefined
export declare function realArtist(s: string | undefined): string | undefined
export declare function metaFromFilename(basename: string): {
  artist?: string
  title: string
  altTitle?: string
}
export declare function parseLrc(lrc: string, totalDuration: number): LyricLineLike[]
export declare function lookupLyrics(
  api: ApiFetch,
  meta: TrackMeta,
  onRetry?: (message: string) => void
): Promise<LookupOutcome>
export declare function searchCandidates(
  api: ApiFetch,
  query: { artist?: string; title?: string; free?: string },
  durationSec: number
): Promise<LyricsCandidate[]>
export declare function lyricsById(
  api: ApiFetch,
  id: number,
  durationSec: number
): Promise<{ lines: LyricLineLike[]; credit: string } | null>
`
)

console.log('build-analysis: wrote mobile/src/gen/analysis-lib.{js,d.ts}')
