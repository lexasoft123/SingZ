#!/usr/bin/env node
/**
 * Materialize the platform-neutral graph document contract under Metro's
 * mobile/ root. The desktop source remains authoritative; --check is the CI
 * drift gate and never writes.
 */
const {
  existsSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
} = require('node:fs')
const { dirname, join } = require('node:path')

const mobileRoot = join(__dirname, '..')
const repoRoot = join(mobileRoot, '..')
const source = join(repoRoot, 'src', 'shared', 'graph-document.ts')
const destination = join(mobileRoot, 'src', 'gen', 'graph-document.ts')
const banner = `// GENERATED by mobile/scripts/sync-graph-document.js — do not edit.
// Authoritative source: src/shared/graph-document.ts
// Regenerate: node mobile/scripts/sync-graph-document.js
`
const expected = banner + readFileSync(source, 'utf8')
const check = process.argv.slice(2).includes('--check')

if (check) {
  if (!existsSync(destination) || readFileSync(destination, 'utf8') !== expected) {
    throw new Error(
      'graph document generated copy is stale; run node mobile/scripts/sync-graph-document.js'
    )
  }
  console.log('sync-graph-document: verified mobile/src/gen/graph-document.ts')
  process.exit(0)
}

mkdirSync(dirname(destination), { recursive: true })
writeFileSync(destination, expected)
console.log('sync-graph-document: wrote mobile/src/gen/graph-document.ts')
