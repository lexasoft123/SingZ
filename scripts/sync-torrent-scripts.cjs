#!/usr/bin/env node
// One DOM/encoding implementation for the three authenticated site browsers.
const {join,resolve}=require('node:path')
const {mkdirSync,writeFileSync}=require('node:fs')
const {createRequire}=require('node:module')
const vm=require('node:vm')
const root=resolve(__dirname,'..')
let esbuild
try{esbuild=require('esbuild')}catch{esbuild=createRequire(join(root,'mobile/package.json'))('esbuild')}
const result=esbuild.buildSync({entryPoints:[join(root,'src/shared/torrent.ts')],bundle:true,platform:'node',format:'cjs',write:false})
const mod={exports:{}};vm.runInNewContext(result.outputFiles[0].text,{module:mod,exports:mod.exports})
const scripts={account:mod.exports.RUTRACKER_ACCOUNT_SCRIPT,search:mod.exports.RUTRACKER_SEARCH_SCRIPT,metadata:mod.exports.RUTRACKER_METADATA_BODY}
const ios=join(root,'mobile/ios/SingzTorrent'),android=join(root,'mobile/android/app/src/main/assets/singz-torrent')
mkdirSync(ios,{recursive:true});mkdirSync(android,{recursive:true})
let header='// GENERATED by scripts/sync-torrent-scripts.cjs. Do not edit.\n#pragma once\n'
for(const [name,script]of Object.entries(scripts)){
 header+='static char const sz_'+name+'_script[] = '+JSON.stringify(script)+';\n'
 writeFileSync(join(android,name+'.js'),script)
}
writeFileSync(join(ios,'rutracker_scripts.h'),header)
console.log('Synced RuTracker browser scripts')
