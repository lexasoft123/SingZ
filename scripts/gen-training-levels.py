#!/usr/bin/env python3
"""Generate the native calibration table from the shared source, without Node."""
import argparse
import pathlib
import re

root = pathlib.Path(__file__).resolve().parents[1]
source = (root / 'src/shared/training-sound-levels.ts').read_text()
boost_match = re.search(r'export const TRAINING_INSTRUMENT_BOOST_DB = (\d+(?:\.\d+)?)\b', source)
if not boost_match:
    raise SystemExit('Missing training boost calibration')
boost = 10 ** (float(boost_match[1]) / 20)
rows = []
for instrument in ('piano', 'electric', 'guitar', 'organ'):
    match = re.search(r'\b' + instrument + r':\s*\[([^]]+)\]', source)
    if not match:
        raise SystemExit(f'Missing calibration: {instrument}')
    values = re.findall(r'\d+\.\d+', match[1])
    if len(values) != 49:
        raise SystemExit(f'Expected 49 gains: {instrument}')
    rows.append('  {{' + ', '.join(values) + '}},')
text = ('// Generated by scripts/gen-training-levels.py; edit the shared TS source.\n'
        '#pragma once\n#include <array>\nnamespace singz {\n'
        + f'inline constexpr double kTrainingBoost = {boost:.17g};\n'
        +
        'inline constexpr std::array<std::array<double, 49>, 4> kTrainingLevels{{\n'
        + '\n'.join(rows) + '\n}};\n}\n')
target = root / 'native/playback/training_levels.generated.h'
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
if args.check:
    if not target.exists() or target.read_text() != text:
        raise SystemExit('Native training calibration is stale')
else:
    target.write_text(text)
